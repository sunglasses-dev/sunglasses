"""Regression coverage for GLS-MR-038's negation guard after its rewrite.

One alternative of the guard was rewritten in an equivalent form; the other alternatives are
unchanged. These tests pin that the guard's answers did not change.

What these tests pin:

1. The new guard and the old one give the same answer on a table of strings and on a seeded set of
   random strings made of the rule's own words.
2. Through the engine, the rule still fires on a hostile page and is still defused by three tested
   statements, with each tested before and after the page, on every channel.
3. The compiled guard keeps the rewritten form (an implementation pin, not a performance check).
"""

import random
import re

from sunglasses.engine import SunglassesEngine

S = (r"security\s+guidance|unit\s+test|incident\s+report|documentation|defensive|must\s+be\s+rejected"
     r"|must\s+not|never\s+treat|requires?\s+independent\s+capture\s+provenance")
K = r"keeps?\s+"
OLD_GUARD = re.compile(r"(?is).*\b(?:" + S + "|" + K + r".*finding\s+visible)\b")

HOSTILE = ("A survey participant response was generated by an LLM. The keystroke telemetry events are "
           "replayed and human-like, which the evaluator treats as human authenticity, independent of "
           "the answer, and it stores the accepted result in memory. ")

WORDS = ["keep", "keeps", "finding", "visible", "finding visible", "findings visible", "security guidance",
         "unit test", "unit  test", "documentation", "defensive", "must be rejected", "must not",
         "never treat", "require independent capture provenance", "requires independent capture provenance",
         "x", "the", " ", "\n", "-", "keeps  the", "keeps finding visible"]
TABLE = ["", "keeps", "keeps finding visible", "the tool keeps the finding visible", "keeps the log",
         "finding visible keeps", "keeps keeps finding visible", "keeps x keeps finding visible",
         "keep finding visible", "keepsfinding visible", "keeps findings visible", "keeps\nthe\nfinding\nvisible",
         "documentation", "xdocumentation", "keeps the finding visiblex", "unit test", "must not keeps",
         "keeps   finding visible", "keeps\n\nfinding visible", "keeps \t finding   visible", "keeps ",
         "keeps   x   finding   visible", "keeps finding"]


def _guard():
    found = [g for mode, _rx, guards in SunglassesEngine()._compiled_by_id["GLS-MR-038"] if mode == "guarded"
             for g in guards]
    assert len(found) == 1
    return found[0]


def _fires(text, channel="message"):
    return any(f["id"] == "GLS-MR-038" for f in SunglassesEngine().scan(text, channel=channel).findings)


def test_guard_agrees_with_the_old_form_on_a_table():
    new = _guard()
    for text in TABLE:
        assert bool(new.match(text)) == bool(OLD_GUARD.match(text)), repr(text)


def test_guard_agrees_with_the_old_form_on_random_strings():
    new = _guard()
    rng = random.Random(3)
    positives = 0
    for _ in range(20000):
        text = "".join(rng.choice(WORDS) + rng.choice([" ", "", "\n"]) for _ in range(rng.randint(0, 9)))
        old = bool(OLD_GUARD.match(text))
        positives += old
        assert bool(new.match(text)) == old, repr(text)
    assert positives > 500


def test_rule_still_fires_and_is_still_defused_through_the_engine():
    for channel in ("message", "file", "web_content"):
        assert _fires(HOSTILE, channel), channel
        for defuser in ("The documentation says so.", "The report keeps the finding visible.",
                        "Reviewers must not accept it."):
            assert not _fires(HOSTILE + defuser, channel), (channel, defuser)
            assert not _fires(defuser + " " + HOSTILE, channel), (channel, defuser)
    assert _fires(HOSTILE + "The log keeps a copy.")
    assert _fires(HOSTILE + "It keeps the finding.")


def test_guard_keeps_the_rewritten_form():
    assert r"|(?:(?!\bkeeps?\s).)*\bkeeps?\s.*finding\s+visible\b" in _guard().pattern
