"""A module written by a script is marked as generated, names a script that checks it, and is
covered by the rule in CONTRIBUTING.md.

A module under `sunglasses/` whose docstring starts `GENERATED by scripts/<name>.py` is written by
that script from other files in the repository. Two branches that change those sources each carry a
different generated file; Git's own conflict handling is unchanged, so the file is regenerated from
the resolved sources and the result is staged. These tests hold the pieces around that:

  * Git's effective attributes for each generated module (the `.gitattributes` in the repository
    root and in each directory above the module, with their patterns) include `linguist-generated`,
    so a review shows the diff collapsed,
  * and leave `merge` unspecified, so no merge driver settles a conflict without the script,
  * the script the docstring names exists and, run with `--check` from the repository root, exits 0,
  * CONTRIBUTING.md carries the regenerate-don't-resolve rule.

Each rule is a function of a repository root that returns the problems it finds. The tests assert
that this repository has none, and, on small repositories built here, that each rule reports the
break it is for. A script that exits 0 on `--check` without comparing anything is not detected.
"""
import ast
import os
import pathlib
import re
import shutil
import subprocess
import sys
import tempfile

import pytest

ROOT = pathlib.Path(__file__).resolve().parents[1]
MARK = re.compile(r"GENERATED by (scripts/[\w./-]+\.py)")
GIT = shutil.which("git")
needs_git = pytest.mark.skipif(GIT is None, reason="git is needed to read the effective attributes")
RULE = "regenerate, don't resolve"


def generated_modules(root):
    """({module path relative to root: the script its docstring names}, [problems]): the modules
    under sunglasses/ whose module docstring (a leading comment may come before it) starts with the
    mark. A file that does not parse is a problem, not a skip."""
    found, problems = {}, []
    for path in sorted((root / "sunglasses").rglob("*.py")):
        rel = path.relative_to(root).as_posix()
        try:
            doc = ast.get_docstring(ast.parse(path.read_text(encoding="utf-8")), clean=False)
        except (SyntaxError, ValueError) as error:
            problems.append("%s: cannot be parsed (%s)" % (rel, error))
            continue
        match = MARK.match(doc or "")
        if match:
            found[rel] = match.group(1)
    return found, problems


def effective_attributes(root, paths, names=("linguist-generated", "merge")):
    """{path: {attribute: value}} as Git resolves them for `paths` from the .gitattributes in root and
    in every directory above each path (the files Git reads for it, whatever the directory is called;
    a symbolic link named .gitattributes is not read, as Git does not read it), in a scratch repository
    with no global configuration, no info/attributes file and the system attributes file switched off
    (GIT_ATTR_NOSYSTEM; no test exercises that one)."""
    with tempfile.TemporaryDirectory() as scratch:
        scratch = pathlib.Path(scratch)
        env = {"PATH": os.environ.get("PATH", ""), "HOME": str(scratch), "GIT_CONFIG_GLOBAL": os.devnull,
               "GIT_CONFIG_NOSYSTEM": "1", "GIT_ATTR_NOSYSTEM": "1", "XDG_CONFIG_HOME": str(scratch)}
        subprocess.run([GIT, "init", "-q", str(scratch)], check=True, env=env, capture_output=True)
        for directory in {pathlib.PurePosixPath(p).parents[i] for p in paths
                          for i in range(len(pathlib.PurePosixPath(p).parents))}:
            source = root / directory / ".gitattributes"
            if source.is_file() and not source.is_symlink():
                target = scratch / directory / ".gitattributes"
                target.parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(source, target)
        done = subprocess.run([GIT, "check-attr", "-z"] + list(names) + ["--"] + list(paths), cwd=scratch,
                              env=env, capture_output=True, check=True)
    fields = done.stdout.decode("utf-8").split("\0")
    table = {}
    for i in range(0, len(fields) - 2, 3):
        table.setdefault(fields[i], {})[fields[i + 1]] = fields[i + 2]
    return table


def marking_problems(root, modules):
    held = effective_attributes(root, modules) if modules else {}
    return ["%s: linguist-generated is %s" % (m, held[m]["linguist-generated"]) for m in sorted(modules)
            if held[m]["linguist-generated"] not in ("set", "true")]


def merge_driver_problems(root, modules):
    held = effective_attributes(root, modules) if modules else {}
    return ["%s: merge is %s" % (m, held[m]["merge"]) for m in sorted(modules)
            if held[m]["merge"] != "unspecified"]


def generator_problems(root, modules, timeout=300):
    """Run each distinct script with --check from root: it must exist and exit 0."""
    problems = []
    for script in sorted(set(modules.values())):
        if not (root / script).is_file():
            problems.append("%s: not found" % script)
            continue
        try:
            done = subprocess.run([sys.executable, script, "--check"], cwd=root, capture_output=True, text=True,
                                  timeout=timeout, env=dict(os.environ, PYTHONDONTWRITEBYTECODE="1"))
        except subprocess.TimeoutExpired:
            problems.append("%s --check: did not finish in %d s" % (script, timeout))
            continue
        if done.returncode:
            problems.append("%s --check: exit %d" % (script, done.returncode))
    return problems


def contributing_problems(root):
    path = root / "CONTRIBUTING.md"
    if not path.is_file() or RULE not in path.read_text(encoding="utf-8"):
        return ["CONTRIBUTING.md does not carry the rule: %s" % RULE]
    return []


@pytest.fixture(scope="module")
def modules():
    found, problems = generated_modules(ROOT)
    assert not problems, problems
    assert found, "no generated module found; the module checks would pass on nothing"
    return found


@needs_git
def test_every_generated_module_is_marked_linguist_generated(modules):
    assert marking_problems(ROOT, modules) == []


@needs_git
def test_no_generated_module_has_a_merge_driver(modules):
    assert merge_driver_problems(ROOT, modules) == []


def test_the_script_a_generated_module_names_exists_and_passes_check(modules):
    assert generator_problems(ROOT, modules) == []


def test_contributing_says_to_regenerate_rather_than_resolve():
    assert contributing_problems(ROOT) == []


# the same rules on repositories built to break each one


def build(tmp_path, files):
    for name, text in files.items():
        target = tmp_path / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")
    return tmp_path


MODULE = '"""GENERATED by scripts/gen_t.py. DO NOT EDIT."""\nX = 1\n'
OK_SCRIPT = "import sys\nsys.exit(0)\n"


def test_a_generated_module_is_found_by_its_docstring_after_a_comment_and_not_by_a_string(tmp_path):
    build(tmp_path, {
        "sunglasses/_a.py": "# a leading comment\n" + MODULE,
        "sunglasses/_b.py": "import os\n" + MODULE,
        "sunglasses/_c.py": '"""An ordinary module."""\nNOTE = "GENERATED by scripts/gen_t.py"\n',
    })
    assert generated_modules(tmp_path) == ({"sunglasses/_a.py": "scripts/gen_t.py"}, [])


def test_a_module_that_does_not_parse_is_reported_and_not_skipped(tmp_path):
    build(tmp_path, {"sunglasses/_a.py": MODULE + "def broken(:\n"})
    found, problems = generated_modules(tmp_path)
    assert found == {} and len(problems) == 1 and problems[0].startswith("sunglasses/_a.py: cannot be parsed")


@needs_git
@pytest.mark.parametrize("attributes,expected", [
    ("# nothing marked\n", ["sunglasses/_t.py: linguist-generated is unspecified"]),
    ("sunglasses/_t.py linguist-generated=true\n", []),
    ("sunglasses/_*.py linguist-generated\n", []),
    ("sunglasses/_t.py linguist-generated=false\n", ["sunglasses/_t.py: linguist-generated is false"]),
    ("sunglasses/_t.py linguist-generated=true\nsunglasses/_t.py -linguist-generated\n",
     ["sunglasses/_t.py: linguist-generated is unset"]),
])
def test_the_marking_rule_reads_the_effective_attributes(tmp_path, attributes, expected):
    build(tmp_path, {"sunglasses/_t.py": MODULE, ".gitattributes": attributes})
    assert marking_problems(tmp_path, {"sunglasses/_t.py": "scripts/gen_t.py"}) == expected


@needs_git
@pytest.mark.parametrize("name,attributes,expected", [
    ("none", "sunglasses/_t.py linguist-generated=true\n", []),
    ("exact_path", "sunglasses/_t.py linguist-generated=true merge=ours\n", ["sunglasses/_t.py: merge is ours"]),
    ("wildcard", "sunglasses/_t.py linguist-generated=true\nsunglasses/*.py merge=ours\n", ["sunglasses/_t.py: merge is ours"]),
    ("whole_tree", "* merge=union\n", ["sunglasses/_t.py: merge is union"]),
    ("unset", "sunglasses/_t.py -merge\n", ["sunglasses/_t.py: merge is unset"]),
    ("macro_binary", "sunglasses/_t.py binary\n", ["sunglasses/_t.py: merge is unset"]),
    ("nested_file", None, ["sunglasses/_t.py: merge is ours"]),
])
def test_the_merge_rule_reads_the_effective_attributes(tmp_path, name, attributes, expected):
    files = {"sunglasses/_t.py": MODULE}
    if attributes is None:
        files["sunglasses/.gitattributes"] = "_t.py merge=ours\n"
    else:
        files[".gitattributes"] = attributes
    build(tmp_path, files)
    assert merge_driver_problems(tmp_path, {"sunglasses/_t.py": "scripts/gen_t.py"}) == expected


@needs_git
@pytest.mark.parametrize("package", ["venv", ".venv", "node_modules", "__pycache__", "build", "pkg/sub"])
def test_the_merge_rule_reads_a_nested_attribute_file_whatever_the_package_is_called(tmp_path, package):
    module = "sunglasses/%s/_t.py" % package
    build(tmp_path, {module: MODULE, ".gitattributes": "%s linguist-generated=true\n" % module,
                     "sunglasses/%s/.gitattributes" % package: "_t.py merge=ours\n"})
    assert generated_modules(tmp_path)[0] == {module: "scripts/gen_t.py"}
    assert merge_driver_problems(tmp_path, {module: "scripts/gen_t.py"}) == ["%s: merge is ours" % module]


def link(tmp_path, name, target):
    try:
        (tmp_path / name).symlink_to(target)
    except (OSError, NotImplementedError):
        pytest.skip("symbolic links cannot be made here")


def git_says(root, paths, names=("linguist-generated", "merge")):
    """What `git check-attr` prints in `root` itself, made a repository here, with the same settings."""
    env = {"PATH": os.environ.get("PATH", ""), "HOME": str(root), "GIT_CONFIG_GLOBAL": os.devnull,
           "GIT_CONFIG_NOSYSTEM": "1", "GIT_ATTR_NOSYSTEM": "1", "XDG_CONFIG_HOME": str(root)}
    subprocess.run([GIT, "init", "-q", str(root)], check=True, env=env, capture_output=True)
    done = subprocess.run([GIT, "check-attr", "-z"] + list(names) + ["--"] + list(paths), cwd=root, env=env,
                          capture_output=True, check=True)
    fields = done.stdout.decode("utf-8").split("\0")
    table = {}
    for i in range(0, len(fields) - 2, 3):
        table.setdefault(fields[i], {})[fields[i + 1]] = fields[i + 2]
    return table


@needs_git
def test_a_symbolic_link_named_gitattributes_is_not_read_in_the_root(tmp_path):
    build(tmp_path, {"sunglasses/_t.py": MODULE, "rules.txt": "sunglasses/_t.py linguist-generated=true\n"})
    link(tmp_path, ".gitattributes", "rules.txt")
    assert marking_problems(tmp_path, {"sunglasses/_t.py": "scripts/gen_t.py"}) == [
        "sunglasses/_t.py: linguist-generated is unspecified"]
    assert effective_attributes(tmp_path, ["sunglasses/_t.py"]) == git_says(tmp_path, ["sunglasses/_t.py"])


@needs_git
def test_a_symbolic_link_named_gitattributes_is_not_read_above_the_module(tmp_path):
    root = "sunglasses/_t.py linguist-generated=true merge=ours\n"
    build(tmp_path, {"sunglasses/_t.py": MODULE, ".gitattributes": root, "sunglasses/rules.txt": "_t.py !merge\n"})
    link(tmp_path, "sunglasses/.gitattributes", "rules.txt")
    modules = {"sunglasses/_t.py": "scripts/gen_t.py"}
    assert merge_driver_problems(tmp_path, modules) == ["sunglasses/_t.py: merge is ours"]
    assert effective_attributes(tmp_path, ["sunglasses/_t.py"]) == git_says(tmp_path, ["sunglasses/_t.py"])
    # the same rules in a regular file are read, so the link above is what changed the answer
    (tmp_path / "sunglasses" / ".gitattributes").unlink()
    (tmp_path / "sunglasses" / ".gitattributes").write_text("_t.py !merge\n", encoding="utf-8")
    assert merge_driver_problems(tmp_path, modules) == []


def test_the_generator_rule_runs_the_script_and_reads_its_exit_status(tmp_path):
    modules = {"sunglasses/_t.py": "scripts/gen_t.py"}
    assert generator_problems(tmp_path, modules) == ["scripts/gen_t.py: not found"]
    build(tmp_path, {"scripts/gen_t.py": OK_SCRIPT})
    assert generator_problems(tmp_path, modules) == []
    build(tmp_path, {"scripts/gen_t.py": "import sys\nsys.exit(1 if '--check' in sys.argv else 0)\n"})
    assert generator_problems(tmp_path, modules) == ["scripts/gen_t.py --check: exit 1"]
    build(tmp_path, {"scripts/gen_t.py": "raise SystemExit('stale')\n"})
    assert generator_problems(tmp_path, modules) == ["scripts/gen_t.py --check: exit 1"]
    build(tmp_path, {"scripts/gen_t.py": "import time\ntime.sleep(30)\n"})
    assert generator_problems(tmp_path, modules, timeout=1) == ["scripts/gen_t.py --check: did not finish in 1 s"]


def test_the_generator_rule_runs_every_script_a_module_names(tmp_path):
    build(tmp_path, {"scripts/gen_a.py": OK_SCRIPT, "scripts/gen_b.py": "raise SystemExit(1)\n"})
    modules = {"sunglasses/_a.py": "scripts/gen_a.py", "sunglasses/_b.py": "scripts/gen_b.py", "sunglasses/_c.py": "scripts/gen_b.py"}
    assert generator_problems(tmp_path, modules) == ["scripts/gen_b.py --check: exit 1"]


@needs_git
def test_a_configured_attributes_file_of_the_machine_takes_no_part(tmp_path, monkeypatch):
    elsewhere = tmp_path / "elsewhere"
    elsewhere.mkdir()
    (elsewhere / "attributes").write_text("* merge=ours\n")
    (elsewhere / "config").write_text("[core]\n\tattributesFile = %s\n" % (elsewhere / "attributes").as_posix())
    monkeypatch.setenv("GIT_CONFIG_GLOBAL", str(elsewhere / "config"))
    monkeypatch.setenv("HOME", str(elsewhere))
    repo = build(tmp_path / "repo", {"sunglasses/_t.py": MODULE, ".gitattributes": "sunglasses/_t.py linguist-generated=true\n"})
    assert merge_driver_problems(repo, {"sunglasses/_t.py": "scripts/gen_t.py"}) == []


def test_the_generator_rule_runs_from_the_repository_root(tmp_path):
    build(tmp_path, {"scripts/gen_t.py": "import os, sys\nsys.exit(0 if os.path.isdir('sunglasses') else 1)\n",
                     "sunglasses/_t.py": MODULE})
    assert generator_problems(tmp_path, {"sunglasses/_t.py": "scripts/gen_t.py"}) == []


def test_the_contributing_rule_needs_the_sentence(tmp_path):
    assert contributing_problems(tmp_path) == ["CONTRIBUTING.md does not carry the rule: " + RULE]
    build(tmp_path, {"CONTRIBUTING.md": "Take either side, then Regenerate. Do not resolve.\n"})
    assert contributing_problems(tmp_path) == ["CONTRIBUTING.md does not carry the rule: " + RULE]
    build(tmp_path, {"CONTRIBUTING.md": "Generated files: " + RULE + ".\n"})
    assert contributing_problems(tmp_path) == []
