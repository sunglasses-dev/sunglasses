#!/usr/bin/env python3
"""Write (or check) the shipped prefilter requirement table, `sunglasses/_requirements_data.py`.

The engine used to derive, on every start, the literals each of its 1,609 rule sources cannot
match without (`_prefilter.requirement`): 454 ms of a 1.2 s start. The derivation is a pure
function of the source text, so it is done here once and shipped; `shipped_requirement` reads
it and falls back to the live derivation for any source the table does not hold.

    python3 tools/gen_requirements.py            # check: exit 1 when the file is not current
    python3 tools/gen_requirements.py --write    # rewrite sunglasses/_requirements_data.py

Run it with --write whenever a rule source or `_prefilter.py` changes. The test
`tests/test_engine_requirement_table.py` fails on a table that is out of date.
Deliberately stdlib only.
"""
from __future__ import annotations

import argparse
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from sunglasses import _prefilter  # noqa: E402
from sunglasses.engine import SunglassesEngine  # noqa: E402

TARGET = ROOT / "sunglasses" / "_requirements_data.py"

HEADER = '''"""GENERATED by tools/gen_requirements.py - do not edit by hand.

The prefilter requirement (the literals a rule cannot match without) of every regex source
the engine loads, keyed by a digest of the full source text. See `_prefilter.shipped_requirement`.
Regenerate with:  python3 tools/gen_requirements.py --write
"""
# fmt: off
'''


def shipped_sources() -> list:
    """Every regex source the default engine hands to the prefilter, sorted."""
    engine = SunglassesEngine()
    return sorted({rx.pattern for _pattern, rxs in engine._regex_patterns for _mode, rx, _extra in rxs})


def render(sources=None) -> str:
    table = _prefilter.build_table(shipped_sources() if sources is None else sources)
    lines = [f"    {json.dumps(key) + ':' + json.dumps(table[key], separators=(',', ':'))!r},"
             for key in sorted(table)]
    return (HEADER + f"FORMAT = {_prefilter.TABLE_FORMAT}\nCOUNT = {len(table)}\nLINES = (\n"
            + "\n".join(lines) + "\n)\n")


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--write", action="store_true", help="rewrite the data file")
    args = parser.parse_args(argv)
    text = render()
    if args.write:
        TARGET.write_text(text, encoding="utf-8")
        print(f"wrote {TARGET.relative_to(ROOT)}")
        return 0
    current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
    if current != text:
        print(f"{TARGET.relative_to(ROOT)} is out of date: run  python3 tools/gen_requirements.py --write")
        return 1
    print(f"{TARGET.relative_to(ROOT)} is current")
    return 0


if __name__ == "__main__":
    sys.exit(main())
