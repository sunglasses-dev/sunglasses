#!/usr/bin/env python3
"""Generate sunglasses/_prefilter_table.py: the prefilter requirement of every rule regex.

Why this exists
---------------
`SunglassesEngine()` asks `_prefilter.requirement()` for the literals each of its
~1,650 regexes cannot match without. That re-parses every regex source and costs
about 440 ms of the 1.6 s a fresh `sunglasses scan` spends starting up. The answer
depends on the regex source, on `_prefilter.py`, and on the interpreter's regex
parser and Unicode tables (it reads `re`'s parse tree and folds characters). It is
computed here once and shipped as data. A table made on one Python must therefore
hold on every Python the project supports: tests/test_prefilter_table.py compares
every entry with a live derivation, and CI runs that test on each version, so a
version that parses a regex differently fails there instead of skipping documents.

The table is a SPEED-UP, never a source of truth:
  * it is keyed by the sha256 of the regex source, so a source the table does not
    know is computed live, exactly as before;
  * it carries the sha256 of `_prefilter.py`, and the engine ignores the whole
    table when that file is not the one the table was generated from, so editing
    the derivation without regenerating costs time and nothing else;
  * tests/test_prefilter_table.py fails when any entry differs from a live
    recomputation, on every Python version CI runs.

Usage
-----
    python3 scripts/gen_prefilter_table.py            # rewrite the table
    python3 scripts/gen_prefilter_table.py --check    # exit 1 if it is stale

Regenerate after ANY change to sunglasses/_prefilter.py or to a rule's regex.
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from sunglasses import _prefilter  # noqa: E402

TABLE_PATH = ROOT / "sunglasses" / "_prefilter_table.py"


def encode(requirement):
    """Canonical source text for one requirement. Equal text == equal requirement."""
    parts = []
    for clause in requirement:
        if isinstance(clause, _prefilter.Clause):
            lits = tuple(sorted(clause.literals))
            classes = ",".join(encode((c,)).rstrip(",") for c in clause.classes)
            parts.append("_C(%r,(%s))" % (lits, classes + ("," if clause.classes else "")))
        elif isinstance(clause, _prefilter.ClassClause):
            parts.append("_R(%r)" % (tuple(clause.ranges),))
        else:
            parts.append("_F(%r)" % (tuple(sorted(clause)),))
    return ",".join(parts) + ("," if parts else "")


def rule_sources():
    """Every regex source the engine asks the prefilter about."""
    from sunglasses.engine import SunglassesEngine
    engine = SunglassesEngine()
    return sorted({rx.pattern
                   for _pattern, regexes in engine._regex_patterns
                   for _mode, rx, _extra in regexes})


def build():
    """The full text of the generated module."""
    digest = _prefilter.file_digest((ROOT / "sunglasses" / "_prefilter.py").read_bytes())
    rows = []
    for source in rule_sources():
        rows.append("    %r: (%s),\n" % (_prefilter.table_key(source),
                                         encode(_prefilter.requirement(source))))
    rows.sort()
    return (
        '"""GENERATED by scripts/gen_prefilter_table.py. DO NOT EDIT BY HAND.\n'
        "\n"
        "The prefilter requirement of every rule regex, so the engine does not re-derive\n"
        "1,650 of them on every start. Keys are sha256 of the regex source. The engine\n"
        "uses this table only while PREFILTER_SHA256 matches sunglasses/_prefilter.py and\n"
        "computes any source it does not hold. Regenerate after a change to either:\n"
        "    python3 scripts/gen_prefilter_table.py\n"
        '"""\n'
        "from sunglasses._prefilter import ClassClause as _R, Clause as _C\n"
        "\n"
        "_F = frozenset\n"
        "\n"
        'PREFILTER_SHA256 = "%s"\n'
        "\n"
        "TABLE = {\n"
        "%s"
        "}\n"
    ) % (digest, "".join(rows))


def main(argv):
    text = build()
    if "--check" in argv:
        current = TABLE_PATH.read_text(encoding="utf-8") if TABLE_PATH.exists() else ""
        if current != text:
            print("STALE: %s differs from a fresh generation" % TABLE_PATH.relative_to(ROOT))
            return 1
        print("OK: %s is current" % TABLE_PATH.relative_to(ROOT))
        return 0
    TABLE_PATH.write_text(text, encoding="utf-8")
    print("wrote %s (%d bytes, %d entries)" % (TABLE_PATH.relative_to(ROOT), len(text), text.count("\n    '")))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
