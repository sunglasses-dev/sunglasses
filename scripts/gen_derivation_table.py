#!/usr/bin/env python3
"""Generate sunglasses/_derivation_table.py: two pure derivations of the shipped rule regexes.

Why this exists
---------------
`SunglassesEngine()` derives, from the text of each shipped rule regex alone:
  * where a caret-led co-occurrence predicate splits into its negation guards and its
    positive core (`SunglassesEngine._split_caret_predicate`, a character scan per regex);
  * for a rule that asks for anchored mode, whether the regex contains a lookaround and the
    longest match it can make (`_prefilter.has_lookaround`, `_prefilter.max_match_length`,
    each a parse of the regex).
Neither answer changes between builds of the package, so they are computed here once and
shipped as data, and the engine looks them up by the sha256 of the source.

A split is stored as offsets into the source, not as text: `(flag_end, ((a, b), ...), core_start)`
rebuilds to `[source[:flag_end] + source[a:b], ...]` and `source[:flag_end] + source[core_start:]`.

The table is a SPEED-UP, never a source of truth:
  * a source the table does not hold is derived live;
  * only a source that ships with the package is looked up: a source outside the shipped set is
    derived live, and a custom rule whose text is identical to a shipped one can use the table;
  * tests/test_derivation_table.py regenerates the table and fails when it differs from the
    shipped one, and compares every entry with a live derivation, on every Python version CI runs.

Usage
-----
    python3 scripts/gen_derivation_table.py            # rewrite the table
    python3 scripts/gen_derivation_table.py --check    # exit 1 if it is stale

Regenerate after ANY change to `_split_caret_predicate`, `_prefilter.has_lookaround`,
`_prefilter.max_match_length`, or a rule's regex.
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from sunglasses import _prefilter  # noqa: E402
from sunglasses.engine import SunglassesEngine, _shipped_regex_sources  # noqa: E402

TABLE_PATH = ROOT / "sunglasses" / "_derivation_table.py"


def split_offsets(source, split):
    """`(flag_end, ((a, b), ...), core_start)` for a live split of `source`, checked by rebuilding it."""
    guards, core = split
    flag_end = 0
    if source.startswith("(?"):
        close = source.index(")")
        if all(c in "aiLmsux" for c in source[2:close]) and close > 2:
            flag_end = close + 1
    flags = source[:flag_end]
    verbose = "x" in flags
    cursor = flag_end
    if verbose:
        cursor += len(source[cursor:]) - len(source[cursor:].lstrip())
    cursor += 2 if source.startswith("\\A", cursor) else 1
    if verbose:
        cursor += len(source[cursor:]) - len(source[cursor:].lstrip())
    spans = []
    for guard in guards:
        body = guard[len(flags):]
        start = cursor + 3                       # past "(?!"
        spans.append((start, start + len(body)))
        cursor = start + len(body) + 1           # past the closing ")"
        if verbose:
            cursor += len(source[cursor:]) - len(source[cursor:].lstrip())
    core_start = len(source) - (len(core) - len(flags))
    offsets = (flag_end, tuple(spans), core_start)
    rebuilt = ([flags + source[a:b] for a, b in offsets[1]], flags + source[core_start:])
    if rebuilt != (list(guards), core):
        raise SystemExit("cannot express this split as offsets: %r" % (source,))
    return offsets


def anchored_sources():
    """Sources of shipped rules that ask for anchored mode, where the engine reads the anchor facts."""
    engine = SunglassesEngine()
    shipped = _shipped_regex_sources()
    return sorted({source
                   for pattern in engine._patterns if pattern.get("anchor_terms")
                   for source in pattern.get("regex", ())
                   if source in shipped})


def build():
    """The full text of the generated module."""
    split_rows, anchor_rows = [], []
    for source in sorted(_shipped_regex_sources()):
        split = SunglassesEngine._split_caret_predicate(source)
        if split is not None:
            split_rows.append("    %r: %r,\n" % (_prefilter.table_key(source), split_offsets(source, split)))
    for source in anchored_sources():
        anchor_rows.append("    %r: %r,\n" % (_prefilter.table_key(source),
                                              (_prefilter.has_lookaround(source),
                                               _prefilter.max_match_length(source))))
    split_rows.sort()
    anchor_rows.sort()
    return (
        '"""GENERATED by scripts/gen_derivation_table.py. DO NOT EDIT BY HAND.\n'
        "\n"
        "Two derivations of the shipped rule regexes, so the engine does not repeat them on every\n"
        "start. Keys are sha256 of the regex source. SPLIT holds the offsets of a caret-led\n"
        "predicate's guards and core; ANCHOR holds (has a lookaround, longest match or None) for\n"
        "a rule that asks for anchored mode. Regenerate after a change to either derivation:\n"
        "    python3 scripts/gen_derivation_table.py\n"
        '"""\n'
        "\n"
        "SPLIT = {\n"
        "%s"
        "}\n"
        "\n"
        "ANCHOR = {\n"
        "%s"
        "}\n"
    ) % ("".join(split_rows), "".join(anchor_rows))


def main(argv):
    text = build()
    if "--check" in argv:
        current = TABLE_PATH.read_text(encoding="utf-8") if TABLE_PATH.exists() else ""
        if current != text:
            print("STALE: %s differs from a fresh generation" % TABLE_PATH.relative_to(ROOT))
            return 1
        print("OK: %s is current" % TABLE_PATH.relative_to(ROOT))
        return 0
    TABLE_PATH.write_text(text, encoding="utf-8")
    print("wrote %s (%d bytes)" % (TABLE_PATH.relative_to(ROOT), len(text)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
